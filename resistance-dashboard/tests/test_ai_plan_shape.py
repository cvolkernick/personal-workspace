"""SuperGrok plans get the same rotation and guards before they are stored."""

from __future__ import annotations

import unittest

from rt_dashboard.workout_planner import (
    default_catalog,
    postshape_ai_workout,
    shape_session_coverage,
    training_continuity,
)

CAP = 14


def _sets(row):
    return int((row.get("prescription") or {}).get("sets") or 0)


def _ai_leg(name, sets, weight=100):
    return {
        "name": name,
        "prescription": {"sets": sets, "reps": 8, "weight_lbs": weight},
    }


class AiLegsPostshape(unittest.TestCase):
    def test_realistic_legs_day_keeps_guards_not_a_template(self):
        workout = {
            "source": "grok",
            "session_type": "legs",
            "is_rest_day": False,
            "exercises": [
                _ai_leg("Hack Squat", 3, 180),
                _ai_leg("Leg Press", 3, 360),
                _ai_leg("RDL", 2, 185),
                _ai_leg("Seated Leg Curl", 2, 90),
                _ai_leg("Calf Raises", 3, 100),
                _ai_leg("Barbell Deadlift", 2, 225),
                _ai_leg("Back Extension Machine", 2, 70),
            ],
            "message": "Generated by SuperGrok.",
        }
        out = postshape_ai_workout(
            workout,
            default_catalog(),
            [],
            goals={"default_hard_sets": 2, "session_working_set_cap": CAP},
            as_of="2026-11-18",
        )
        got = [(row["id"], _sets(row)) for row in out["exercises"]]
        self.assertLessEqual(sum(sets for _, sets in got), CAP)
        self.assertEqual(out["source"], "grok")
        ids = [row["id"] for row in out["exercises"]]
        hinges = [
            eid for eid in ids
            if eid in {"rdl", "barbell-deadlift", "trap-bar-deadlift", "back-extension", "back-extension-45"}
        ]
        self.assertEqual(len(hinges), 1, ids)
        self.assertLess(ids.index("hack-squat"), ids.index("leg-press"))
        self.assertIn("hack-squat", ids)
        self.assertIn("leg-press", ids)
        added = [
            row for row in out["exercises"]
            if row["id"] not in {
                "hack-squat", "leg-press", "rdl", "seated-leg-curls",
                "calf-raises", "barbell-deadlift", "back-extension",
            }
        ]
        for row in added:
            self.assertIsNone((row.get("prescription") or {}).get("weight_lbs"), row["id"])

    def test_abs_lands_on_two_days_at_two_sets(self):
        catalog = default_catalog()
        goals = {"default_hard_sets": 2, "session_working_set_cap": CAP, "rotation": ["push", "pull", "legs"]}
        days = [
            ("2026-11-16", "push"),
            ("2026-11-17", "pull"),
            ("2026-11-18", "legs"),
            ("2026-11-19", "push"),
            ("2026-11-20", "pull"),
        ]
        history = []
        abs_days = []
        from rt_dashboard.models import ExerciseEntry, Session, SetEntry

        for day, letter in days:
            raw = {
                "source": "grok",
                "session_type": letter,
                "is_rest_day": False,
                "exercises": [
                    {
                        "name": "DB Flat Press" if letter == "push" else (
                            "Seated Cable Row" if letter == "pull" else "Leg Press"
                        ),
                        "prescription": {"sets": 2, "reps": 8, "weight_lbs": 100},
                    }
                ],
            }
            out = postshape_ai_workout(
                raw, catalog, history, goals=goals, as_of=day
            )
            abs_rows = [
                row for row in out["exercises"]
                if row.get("id") in {"ab-crunch-machine", "cable-crunch", "roman-chair-raise"}
            ]
            self.assertLessEqual(sum(_sets(row) for row in out["exercises"]), CAP)
            if abs_rows:
                abs_days.append(letter)
                self.assertEqual(len(abs_rows), 1)
                self.assertEqual(_sets(abs_rows[0]), 2)
            history.append(
                Session(
                    date=day,
                    session_type=letter,
                    exercises=[
                        ExerciseEntry(
                            name=row["name"],
                            sets=[SetEntry(weight_lbs=100, sets=_sets(row), reps=8)],
                        )
                        for row in out["exercises"]
                        if row.get("id") == "ab-crunch-machine" or _sets(row)
                    ],
                )
            )
        self.assertEqual(abs_days, ["push", "legs"])


class AbsCapTrim(unittest.TestCase):
    def test_accessories_trim_before_abs_drops_below_two(self):
        """A full push day keeps 2 abs sets by cutting another isolation first."""
        rows = [
            {
                "id": "db-flat-press",
                "name": "DB Flat Press",
                "movement": "compound",
                "priority": 10,
                "primary_muscles": ["chest"],
                "secondary_muscles": [],
                "prescription": {"sets": 2, "reps": 8, "weight_lbs": 50},
            },
            {
                "id": "smith-flat-bench",
                "name": "Smith Flat Bench",
                "movement": "compound",
                "priority": 9,
                "primary_muscles": ["chest"],
                "secondary_muscles": [],
                "prescription": {"sets": 2, "reps": 8, "weight_lbs": 60},
            },
            {
                "id": "lateral-raises",
                "name": "Lateral Raises",
                "movement": "isolation",
                "priority": 4,
                "primary_muscles": ["side_delts"],
                "secondary_muscles": [],
                "prescription": {"sets": 10, "reps": 12, "weight_lbs": 15},
            },
        ]
        catalog = default_catalog()
        from rt_dashboard.workout_planner import catalog_exercises

        pool = [
            ex for ex in catalog_exercises(catalog, available_only=True)
            if "push" in (ex.get("session_types") or [])
        ]
        shaped = shape_session_coverage(
            rows,
            st="push",
            pool=pool,
            pool_by_id={ex["id"]: ex for ex in pool},
            pin_ids=[],
            session_cap=CAP,
            default_hard=2,
            sessions=[],
            by_id={ex["id"]: ex for ex in pool},
            catalog=catalog,
            day="2026-11-18",
            sec_frac=0.5,
            already_logged=lambda _row: False,
            recovery_score=80,
            continuity=training_continuity(1),
            recovery_rhr_under=False,
            equipment=None,
            deload=False,
            weighins=None,
            today_logged_ids=[],
            today_logged_names=[],
            drop_extras=False,
            force_counts=False,
        )
        by_id = {row["id"]: row for row in shaped}
        abs_ids = [eid for eid in by_id if eid in {"ab-crunch-machine", "cable-crunch", "roman-chair-raise"}]
        self.assertEqual(len(abs_ids), 1, list(by_id))
        self.assertEqual(_sets(by_id[abs_ids[0]]), 2)
        if "lateral-raises" in by_id:
            self.assertLess(_sets(by_id["lateral-raises"]), 10)
        # DB Flat is the main opener, so the post-shape raises it to 4.
        # The other press stays at the written 2.
        self.assertEqual(_sets(by_id["db-flat-press"]), 4)
        self.assertEqual(_sets(by_id["smith-flat-bench"]), 2)
        self.assertLessEqual(sum(_sets(row) for row in shaped), CAP)
